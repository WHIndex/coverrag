ASQA_DOCS="${ASQA_DOCS:-data/asqa_eval_gtr_top100_bge_reranked.json}"
ELI5_DOCS="${ELI5_DOCS:-data/eli5_eval_bm25_top100_bge_reranked.json}"
QAMPARI_DOCS="${QAMPARI_DOCS:-data/qampari_eval_gtr_top100_bge_reranked.json}"

ASQA_RAW_OUT="$API_RAW_DIR/asqa-api-crag.json"
ELI5_RAW_OUT="$API_RAW_DIR/eli5-api-crag.json"
QAMPARI_RAW_OUT="$API_RAW_DIR/qampari-api-crag.json"

API_CRAG_WORKERS="${API_CRAG_WORKERS:-2}"
API_CRAG_LIMIT="${API_CRAG_LIMIT:-}"
API_CRAG_EVALUATOR="${API_CRAG_EVALUATOR:-api}"
API_CRAG_MAX_DOC_POOL="${API_CRAG_MAX_DOC_POOL:-100}"
API_CRAG_MAX_EVAL_DOCS="${API_CRAG_MAX_EVAL_DOCS:-8}"
