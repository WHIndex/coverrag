#!/usr/bin/env bash
# API CRAG-style base generation + COVER-RAG v13 plug-in.
#
# CRAG is retrieval-side correction: evaluate retrieved documents, filter or
# supplement them from the top100 pool, then generate a citation-grounded draft.
# COVER-RAG is answer-side correction: audit/repair the generated answer at
# claim level. This script runs both v0 (raw CRAG) and v3 (COVER-CRAG).
#
# Launch:
#   nohup bash scripts/run_api_crag_cover_nohup.sh \
#     > logs/api_crag_cover_v13_$(date +%Y%m%d_%H%M%S).log 2>&1 &

set -uo pipefail

