API_CRAG_MAX_TOKENS="${API_CRAG_MAX_TOKENS:-450}"
FORCE_API_CRAG="${FORCE_API_CRAG:-0}"

run_step() {
  local label="$1"
  shift
  echo
  echo "=== $label ==="
  echo "+ $*"
  "$@"
  local status=$?
  if [ "$status" -ne 0 ]; then
    echo "FAILED: $label exited with $status"
    exit "$status"
  fi
}

run_api_crag_one() {
  local dataset="$1"
  local input="$2"
  local docs="$3"
  local output="$4"
  if [ ! -f "$input" ]; then
    echo "WARNING: skip $dataset because input missing: $input"
    return 0
  fi
  if [ "$FORCE_API_CRAG" != "1" ] && [ -f "$output" ]; then
    echo "API CRAG output exists, skip $dataset: $output"
    return 0
  fi
  local cmd=(
    "$PYTHON" scripts/run_api_crag.py
    --input "$input"
    --output "$output"
    --dataset "$dataset"
    --model "$API_CRAG_MODEL"
    --candidate-docs-file "$docs"
    --evaluator "$API_CRAG_EVALUATOR"
    --max-doc-pool "$API_CRAG_MAX_DOC_POOL"
    --max-eval-docs "$API_CRAG_MAX_EVAL_DOCS"
    --max-output-docs "$API_CRAG_MAX_OUTPUT_DOCS"
    --refined-sentences-per-doc "$API_CRAG_REFINED_SENTENCES"
    --max-tokens "$API_CRAG_MAX_TOKENS"
    --workers "$API_CRAG_WORKERS"
    --cache-file "cache/api_crag_${dataset}_${API_CRAG_MODEL}_cache.json"
    --pretty
  )
  if [ -n "$API_CRAG_LIMIT" ]; then
    cmd+=(--limit "$API_CRAG_LIMIT")
  fi
  run_step "Generate API CRAG $dataset" "${cmd[@]}"
}

